-- Class Feud custom boards.
-- Run this in the Supabase SQL Editor.
--
-- Mirrors the quiz_items pattern: one row per survey round, grouped into a
-- board by board_number. Board-level fields (title, subtitle, is_public,
-- hashtags, author) are duplicated on every row; the thumbnail is stored only
-- on the first row so a large GIF isn't duplicated per round.
--
-- Round shape:
-- - prompt: the survey question read to the class (prompt OR image is required
--   by the client).
-- - image: base64 data URL or plain URL (picture or GIF).
-- - answers: jsonb array of up to 10 entries, best answer first:
--     [{ "text": "Fridge", "points": 31, "aliases": ["refrigerator"] }, ...]
--   `points` is what the team scores for finding that answer; `aliases` are
--   extra spellings the answer matcher also accepts.

create table if not exists public.feud_items (
  id bigint generated by default as identity primary key,
  board_number bigint not null,
  title text not null,
  subtitle text not null default '',
  prompt text not null default '',
  image text not null default '',
  answers jsonb not null default '[]'::jsonb,
  thumbnail text not null default '',
  is_public boolean not null default true,
  hashtags text[] not null default '{}',
  author_id uuid not null references auth.users (id) on delete cascade,
  created_at timestamptz not null default now(),
  -- Same cap as the other game tables (~1.5MB raw image + base64 overhead).
  constraint feud_items_image_size_limit check (length(image) <= 2200000),
  constraint feud_items_thumbnail_size_limit check (length(thumbnail) <= 2200000),
  constraint feud_items_answers_is_array check (jsonb_typeof(answers) = 'array'),
  constraint feud_items_answers_count check (jsonb_array_length(answers) between 1 and 10)
);

create index if not exists feud_items_board_number_idx
  on public.feud_items (board_number);

alter table public.feud_items enable row level security;

drop policy if exists "Public can read public feud items" on public.feud_items;
drop policy if exists "Authenticated users can create their own feud items" on public.feud_items;
drop policy if exists "Authenticated owners can update their own feud items" on public.feud_items;
drop policy if exists "Authenticated owners can delete their own feud items" on public.feud_items;

create policy "Public can read public feud items"
on public.feud_items
for select
to anon, authenticated
using (
  is_public = true
  or author_id = auth.uid()
);

create policy "Authenticated users can create their own feud items"
on public.feud_items
for insert
to authenticated
with check (author_id = auth.uid());

create policy "Authenticated owners can update their own feud items"
on public.feud_items
for update
to authenticated
using (author_id = auth.uid())
with check (author_id = auth.uid());

create policy "Authenticated owners can delete their own feud items"
on public.feud_items
for delete
to authenticated
using (author_id = auth.uid());
