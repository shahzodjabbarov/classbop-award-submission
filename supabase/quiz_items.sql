-- Quiz-Bop custom quizzes.
-- Run this in the Supabase SQL Editor.
--
-- Mirrors the pictionary_items pattern: one row per question, grouped into a
-- quiz by match_number. Quiz-level fields (title, subtitle, is_public,
-- hashtags, author) are duplicated on every row; the thumbnail is stored only
-- on the first row so a large GIF isn't duplicated per question.
--
-- Question shape:
-- - question / hint: text shown to students (question OR image is required by
--   the client; hint is optional).
-- - image: base64 data URL or plain URL (picture or GIF).
-- - answer: the reveal text (for multiple choice, the correct choice's text).
-- - choices + correct_choice: set only for multiple-choice questions.
-- - points: score awarded for a correct answer (5, 10, or 15).

create table if not exists public.quiz_items (
  id bigint generated by default as identity primary key,
  match_number bigint not null,
  title text not null,
  subtitle text not null default '',
  question text not null default '',
  hint text not null default '',
  answer text not null default '',
  image text not null default '',
  choices jsonb,
  correct_choice integer,
  points integer not null default 10,
  thumbnail text not null default '',
  is_public boolean not null default true,
  hashtags text[] not null default '{}',
  author_id uuid not null references auth.users (id) on delete cascade,
  created_at timestamptz not null default now(),
  -- Same cap as the Guess The Price tables (~1.5MB raw image + base64 overhead).
  constraint quiz_items_image_size_limit check (length(image) <= 2200000),
  constraint quiz_items_thumbnail_size_limit check (length(thumbnail) <= 2200000),
  constraint quiz_items_points_allowed check (points in (5, 10, 15))
);

create index if not exists quiz_items_match_number_idx
  on public.quiz_items (match_number);

alter table public.quiz_items enable row level security;

drop policy if exists "Public can read public quiz items" on public.quiz_items;
drop policy if exists "Authenticated users can create their own quiz items" on public.quiz_items;
drop policy if exists "Authenticated owners can update their own quiz items" on public.quiz_items;
drop policy if exists "Authenticated owners can delete their own quiz items" on public.quiz_items;

create policy "Public can read public quiz items"
on public.quiz_items
for select
to anon, authenticated
using (
  is_public = true
  or author_id = auth.uid()
);

create policy "Authenticated users can create their own quiz items"
on public.quiz_items
for insert
to authenticated
with check (author_id = auth.uid());

create policy "Authenticated owners can update their own quiz items"
on public.quiz_items
for update
to authenticated
using (author_id = auth.uid())
with check (author_id = auth.uid());

create policy "Authenticated owners can delete their own quiz items"
on public.quiz_items
for delete
to authenticated
using (author_id = auth.uid());
