-- ClassBop custom Pictionary sets.
-- Run this in the Supabase SQL Editor when provisioning a new project.

create table if not exists public.pictionary_items (
  id bigint generated by default as identity primary key,
  match_number bigint not null,
  title text not null,
  word text not null,
  image text not null default '',
  is_public boolean not null default true,
  hashtags text[] not null default '{}',
  thumbnail text not null default '',
  author_id uuid not null references auth.users (id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint pictionary_items_title_size check (length(title) between 1 and 120),
  constraint pictionary_items_word_size check (length(word) between 1 and 120),
  constraint pictionary_items_image_size check (length(image) <= 2200000),
  constraint pictionary_items_thumbnail_size check (length(thumbnail) <= 2200000),
  constraint pictionary_items_hashtag_count check (cardinality(hashtags) <= 8)
);

create index if not exists pictionary_items_match_number_idx
  on public.pictionary_items (match_number);

create index if not exists pictionary_items_author_id_idx
  on public.pictionary_items (author_id);

alter table public.pictionary_items enable row level security;

drop policy if exists "Public can read public pictionary items" on public.pictionary_items;
drop policy if exists "Authenticated users can create their own pictionary items" on public.pictionary_items;
drop policy if exists "Authenticated owners can update their own pictionary items" on public.pictionary_items;
drop policy if exists "Authenticated owners can delete their own pictionary items" on public.pictionary_items;

create policy "Public can read public pictionary items"
on public.pictionary_items
for select
to anon, authenticated
using (
  is_public = true
  or author_id = auth.uid()
);

create policy "Authenticated users can create their own pictionary items"
on public.pictionary_items
for insert
to authenticated
with check (author_id = auth.uid());

create policy "Authenticated owners can update their own pictionary items"
on public.pictionary_items
for update
to authenticated
using (author_id = auth.uid())
with check (author_id = auth.uid());

create policy "Authenticated owners can delete their own pictionary items"
on public.pictionary_items
for delete
to authenticated
using (author_id = auth.uid());
