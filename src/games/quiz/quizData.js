export function getQuizMatch(matchId) {
  return QUIZ_MATCHES.find((match) => match.id === matchId);
}

export function pickQuizQuestions(match, length, shouldShuffle) {
  const questions = [...match.questions];

  if (shouldShuffle) {
    for (let index = questions.length - 1; index > 0; index -= 1) {
      const swapIndex = Math.floor(Math.random() * (index + 1));
      [questions[index], questions[swapIndex]] = [questions[swapIndex], questions[index]];
    }
  }

  return questions.slice(0, length === 'ALL' ? questions.length : length);
}
